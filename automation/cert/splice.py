"""Splice generated certificates into `Isoperim/Isoperim_aux2.lean`.

This file was automatically generated by Claude.

The certificate generators print Lean code on stdout; this script replaces the region between
the lines `-- BEGIN GENERATED <part> ...` and `-- END GENERATED <part>` of
`Isoperim/Isoperim_aux2.lean` by that output. Usage (from the repository root):

    py automation/cert/eqn_5_11_certs.py <anc/partitions.py> | py automation/cert/splice.py eqn_5_11
    py automation/cert/poincare_certs.py dir  | py automation/cert/splice.py poincare_dir
    py automation/cert/poincare_certs.py dirx | py automation/cert/splice.py poincare_dirx

If the generated text is a complete Lean file (it contains `@[expose] public section`, as the
output of `poincare_certs.py` does), only the part after that line is inserted; its file header
and module docstring are kept in `Isoperim_aux2.lean` as the docstring of the part.
"""
import sys

TARGET = "Isoperim/Isoperim_aux2.lean"


def main():
    part = sys.argv[1]
    sys.stdin.reconfigure(encoding="utf-8")
    gen = sys.stdin.read()
    key = "@[expose] public section"
    if key in gen:
        gen = gen[gen.index(key) + len(key):]
    gen = gen.strip("\n")
    lines = open(TARGET, encoding="utf8").read().split("\n")
    begin = next(i for i, s in enumerate(lines) if s.startswith(f"-- BEGIN GENERATED {part} "))
    end = next(i for i, s in enumerate(lines) if s == f"-- END GENERATED {part}")
    lines[begin + 1:end] = gen.split("\n")
    with open(TARGET, "w", encoding="utf8", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
