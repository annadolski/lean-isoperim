    l = dec(v - mp.mpf("1e-12"), 15, False)
    lp = dec(v + mp.mpf("1e-12"), 15, True)
    s = dec(mp.sqrt(mpf(Fr(l))) - mp.mpf("1e-15"), 15, False)
    S = dec(mp.sqrt(mpf(Fr(lp))) + mp.mpf("1e-15"), 15, True)
    assert Fr(s) ** 2 <= Fr(l) and Fr(lp) <= Fr(S) ** 2 and Fr(s) >= 0
