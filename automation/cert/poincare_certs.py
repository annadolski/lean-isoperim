def enclose(v, margin="1e-10", digits=13):
    return dec(v - mp.mpf(margin), digits, False), dec(v + mp.mpf(margin), digits, True)


def two_times(s):
    q = 2 * Fr(s)
    return f"{q.numerator}/{q.denominator}"


